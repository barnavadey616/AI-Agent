@tool(name="export_markdown_report", description="Save a formatted markdown executive report to the reports directory.")
def export_markdown_report(title: str, content: str, filename: str = "report.md") -> str:
    """Exports markdown content with header and timestamp."""
    p = config.REPORTS_DIR / filename
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    header = f"# {title}\n\n*Generated by TaskFlow AI on {timestamp}*\n\n---\n\n"
    full_text = header + content

    with open(p, "w", encoding="utf-8") as f:
        f.write(full_text)

    return f"Report saved successfully to {p}"

