@tool(name="format_email_draft", description="Format a customer or team email response draft.")
def format_email_draft(recipient: str, subject: str, body: str, urgency: str = "Normal", category: str = "Support") -> Dict[str, Any]:
    """Prepares a formatted draft response for human approval or automated dispatch."""
    draft = {
        "recipient": recipient,
        "subject": subject,
        "body": body.strip(),
        "urgency": urgency,
        "category": category,
        "timestamp": datetime.datetime.now().isoformat(),
        "status": "Ready for Review"
    }
    
    # Save draft to reports
    slug = "".join(c for c in subject if c.isalnum() or c in "-_ ")[:30].strip().replace(" ", "_")
    draft_file = config.REPORTS_DIR / f"email_draft_{slug}.json"
    with open(draft_file, "w", encoding="utf-8") as f:
        import json
        json.dump(draft, f, indent=2)

    return draft
