@tool(
    name="analyze_delivery_delays",
    description="Analyzes Amazon order and logistics delivery tracking data, identifies root causes of transit delays, and generates priority re-routing actions.",
    parameters={
        "type": "object",
        "properties": {
            "carrier_filter": {
                "type": "string",
                "description": "Optional carrier filter (e.g., 'AMZL', 'UPS', 'FedEx', or 'ALL').",
            },
            "origin_fc": {
                "type": "string",
                "description": "Optional origin Fulfillment Center code (e.g., 'ONT8', 'JFK8', 'ORD4').",
            }
        },
    },
)
def analyze_delivery_delays(carrier_filter: str = "ALL", origin_fc: str = "ALL") -> dict:
    """Analyze delivery tracking data and diagnose delays."""
    _ensure_reports_dir()
    csv_path = AMAZON_DATA_DIR / "delivery_logistics.csv"
    if not csv_path.exists():
        return {"error": f"Logistics dataset not found at {csv_path}"}

    records = []
    with open(csv_path, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if carrier_filter != "ALL" and row["carrier"].upper() != carrier_filter.upper():
                continue
            if origin_fc != "ALL" and row["origin_fc"].upper() != origin_fc.upper():
                continue
            records.append(row)

    total_orders = len(records)
    delayed_orders = [r for r in records if "Delayed" in r["current_status"]]
    on_time_orders = [r for r in records if r not in delayed_orders]

    delay_causes = {}
    carriers_affected = {}
    high_risk_shipments = []

    for r in delayed_orders:
        cause = r["delay_reason"]
        delay_causes[cause] = delay_causes.get(cause, 0) + 1
        c = r["carrier"]
        carriers_affected[c] = carriers_affected.get(c, 0) + 1
        if r["risk_level"] in ["HIGH", "CRITICAL"]:
            high_risk_shipments.append(r)

    total_delay_hours = sum(float(r["delay_hours"]) for r in delayed_orders) if delayed_orders else 0.0
    avg_delay_hours = round(total_delay_hours / len(delayed_orders), 1) if delayed_orders else 0.0

    # Recommended Actions
    actions = []
    if "SORT_JAM_ONT8" in delay_causes:
        actions.append("Initiate AMZL Secondary Hub Bypass: Route Southern California outbound parcels through DLA4 instead of ONT8 sortation line.")
    if "WEATHER_STORM_MIDWEST" in delay_causes:
        actions.append("Corridor Freeze Protocol (SOP-SUPPLY-DISRUPT-02): Divert Chicago/ORD4 line-hauls via I-70 Southern bypass and alert affected Prime customers.")
    if "CARRIER_CAPACITY_OVERFLOW" in delay_causes:
        actions.append("DSP Fleet Flex Injection: Transfer 250 overflow packages from FedEx Seattle hubs directly to dedicated Amazon AMZL delivery stations.")

    # Generate Markdown Report Artifact
    report_filename = "amazon_delivery_delays_report.md"
    report_path = REPORTS_DIR / report_filename
    md_content = f"""# Amazon Logistics Operational Intelligence: Delivery Delays Root-Cause Analysis
*Generated by F.R.Y.D.A.Y Autonomous Operations Copilot | Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*

## Executive Summary
- **Audited Shipments:** {total_orders}
- **On-Time Rate:** {round((len(on_time_orders) / total_orders * 100), 1) if total_orders else 0}%
- **Delayed Shipments:** {len(delayed_orders)} (Average Delay: **{avg_delay_hours} hours**)
- **Critical Risk Escalations:** {len(high_risk_shipments)}

## Primary Root Causes Identified
| Delay Cause Code | Impacted Orders | Severity | Description |
| :--- | :--- | :--- | :--- |
"""
    for cause, count in delay_causes.items():
        sev = "CRITICAL" if "WEATHER" in cause or "SORT_JAM" in cause else "HIGH"
        md_content += f"| `{cause}` | **{count}** | `{sev}` | Logistics network event |\n"

    md_content += """
## High-Priority Shipments Requiring Intervention
| Order ID | Tracking ID | Origin FC | Dest Station | Carrier | Delay (Hrs) | Root Cause |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
"""
    for s in high_risk_shipments[:6]:
        md_content += f"| `{s['order_id']}` | `{s['tracking_id']}` | {s['origin_fc']} | {s['dest_station']} | **{s['carrier']}** | {s['delay_hours']}h | {s['delay_reason']} |\n"

    md_content += "\n## Autonomous Action Directives\n"
    for idx, act in enumerate(actions, 1):
        md_content += f"{idx}. **{act}**\n"

    report_path.write_text(md_content, encoding="utf-8")

    return {
        "status": "success",
        "total_audited": total_orders,
        "delayed_count": len(delayed_orders),
        "avg_delay_hours": avg_delay_hours,
        "primary_causes": delay_causes,
        "carriers_affected": carriers_affected,
        "high_risk_count": len(high_risk_shipments),
        "recommended_actions": actions,
        "report_file": report_filename,
    }


