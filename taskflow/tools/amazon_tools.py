@tool(
    name="query_amazon_sops",
    description="Retrieves authoritative Amazon Standard Operating Procedures (SOPs) for Fulfillment Center safety, concession matrices, and logistics dispatch protocols.",
    parameters={
        "type": "object",
        "properties": {
            "query_topic": {
                "type": "string",
                "description": "Topic or keyword (e.g. 'conveyor safety', 'concession policy', 'delivery delay protocol', 'defective returns').",
            }
        },
        "required": ["query_topic"]
    },
)
def query_amazon_sops(query_topic: str) -> dict:
    """Retrieve official Amazon internal SOP documents."""
    json_path = AMAZON_DATA_DIR / "amazon_internal_sops.json"
    if not json_path.exists():
        return {"error": f"SOP repository not found at {json_path}"}

    with open(json_path, mode="r", encoding="utf-8") as f:
        sops = json.load(f)

    q = query_topic.lower()
    matches = []
    for doc in sops:
        score = 0
        if any(w in doc["title"].lower() for w in q.split()):
            score += 3
        if any(t in q for t in doc.get("tags", [])):
            score += 2
        if any(w in doc["content"].lower() for w in q.split()):
            score += 1
        if score > 0:
            matches.append((score, doc))

    matches.sort(key=lambda x: x[0], reverse=True)
    results = [m[1] for m in matches[:2]] if matches else sops[:1]

    return {
        "status": "success",
        "query": query_topic,
        "matched_count": len(results),
        "sops": results
    }


