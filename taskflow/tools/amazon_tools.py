@tool(
    name="analyze_return_anomalies",
    description="Analyzes Amazon product returns data, identifies ASINs with abnormal return rates (>15%), clusters return reason codes, and triggers quality chargebacks.",
    parameters={
        "type": "object",
        "properties": {
            "threshold_pct": {
                "type": "number",
                "description": "Minimum return rate percentage threshold to flag (default: 10.0).",
            },
            "category": {
                "type": "string",
                "description": "Optional category filter (e.g., 'Electronics', 'Office_Tech', or 'ALL').",
            }
        },
    },
)
def analyze_return_anomalies(threshold_pct: float = 10.0, category: str = "ALL") -> dict:
    """Analyze high product return rates and isolate defective ASINs."""
    _ensure_reports_dir()
    csv_path = AMAZON_DATA_DIR / "returns_reverse_logistics.csv"
    if not csv_path.exists():
        return {"error": f"Returns dataset not found at {csv_path}"}

    flagged_asins = []
    with open(csv_path, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if category != "ALL" and row["category"].lower() != category.lower():
                continue
            rate = float(row["return_rate_pct"])
            if rate >= threshold_pct:
                flagged_asins.append(row)

    # Sort descending by return rate
    flagged_asins.sort(key=lambda x: float(x["return_rate_pct"]), reverse=True)

    action_recommendations = []
    for item in flagged_asins:
        rate = float(item["return_rate_pct"])
        if rate >= 20.0:
            action_recommendations.append(
                f"Suppress ASIN {item['asin']} ('{item['product_title'][:30]}...'): "
                f"Extreme return rate ({rate}%). Primary defect: {item['primary_reason_code']}. Initiate vendor chargeback."
            )
        elif "INACCURATE_PDP" in item["secondary_reason_code"]:
            action_recommendations.append(
                f"Notify Vendor for ASIN {item['asin']}: Detail page discrepancy reported by customers ('{item['customer_feedback_snippet'][:40]}...'). Update technical specs."
            )

    report_filename = "amazon_returns_analysis_report.md"
    report_path = REPORTS_DIR / report_filename
    md_content = f"""# Amazon Reverse Logistics: Defective ASIN & Return Code Audit
*Generated by F.R.Y.D.A.Y Autonomous Operations Copilot | Standard: SOP-REVERSE-LOG-09*

## Audit Parameters
- **Return Rate Anomaly Threshold:** `{threshold_pct}%`
- **Category Filter:** `{category}`
- **Flagged Defective ASINs:** **{len(flagged_asins)}**

## Anomalous ASIN Registry
| ASIN | Product Title | Category | Units Sold | Returned | Return Rate | Primary Reason | Customer Defect Claim |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |
"""
    for item in flagged_asins:
        md_content += f"| `{item['asin']}` | {item['product_title'][:32]}... | {item['category']} | {item['units_sold']} | {item['units_returned']} | **{item['return_rate_pct']}%** | `{item['primary_reason_code']}` | {item['customer_feedback_snippet'][:45]}... |\n"

    md_content += "\n## Autonomous Vendor & Catalog Enforcement Actions\n"
    for idx, act in enumerate(action_recommendations, 1):
        md_content += f"{idx}. **{act}**\n"

    report_path.write_text(md_content, encoding="utf-8")

    return {
        "status": "success",
        "flagged_count": len(flagged_asins),
        "flagged_asins": flagged_asins,
        "recommended_actions": action_recommendations,
        "report_file": report_filename,
    }


